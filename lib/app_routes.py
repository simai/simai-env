#!/usr/bin/env python3
"""Render the nginx routes of a service site (profile node) from its release.

Usage: app_routes.py <release-root> <project> <port> <site-root> <release-id> <routes-out> <maps-out>

Without a "static" section the site is a plain proxy to the service. With
one, nginx serves the static root of the release and sends only the listed
route prefixes to the service, with named header sets per path, cache rules
by query argument or URI pattern, deny patterns and a release header:

  "static":    {"root": "public", "fallback": "/index.html" | "404"}
  "routes":    [{"path": "/api/", "to": "service", "headers": ["api"]}]
  "headers":   {"page": {"Content-Security-Policy": "...", ...}, ...}
  "page":      {"headers": ["page"], "cache": "no-cache" | "<rule>"}
  "locations": [{"path": "/simai/", "exact": false, "headers": ["page"],
                 "cors": true, "cache": "<rule>", "default_type": "font/ttf",
                 "try": "file" | "dir"}]
  "cache":     {"<rule>": {"arg": "sf_v", "values": ["..."], "value": "...", "default": "no-cache"}
                {"<rule>": {"uri": "<regex>", "value": "...", "default": "no-cache"}}
  "deny":      ["<regex>", ...]
  "release_header": "X-App-Release"
  "gzip_types": ["text/css", ...]

Every value is validated before it reaches nginx: header names come from an
allowlist, values and patterns cannot contain quotes, backslash at the end,
'$' (except a final regex anchor) or braces outside regex quantifiers.
Exits 2 with a message on invalid input.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HEADER_NAMES = {
    "content-security-policy", "content-security-policy-report-only", "permissions-policy",
    "referrer-policy", "x-frame-options", "x-content-type-options", "strict-transport-security",
    "cross-origin-resource-policy", "cross-origin-opener-policy", "cross-origin-embedder-policy",
    "access-control-allow-origin", "access-control-allow-methods", "access-control-allow-headers",
    "access-control-expose-headers", "access-control-max-age", "timing-allow-origin", "x-robots-tag",
    "cache-control", "vary",
}
NAME = re.compile(r"^[a-z][a-z0-9_-]{0,30}$")
PATH = re.compile(r"^/[A-Za-z0-9._~/-]{0,200}$")
VALUE = re.compile(r"^[\x20-\x7e]{0,2000}$")
CACHE_VALUE = re.compile(r"^[a-z0-9=, -]{1,100}$")
MIME = re.compile(r"^[a-z0-9.+-]{1,60}/[a-z0-9.+-]{1,80}$")
ARG = re.compile(r"^[a-z0-9_]{1,40}$")
TOKEN = re.compile(r"^[A-Za-z0-9._:-]{1,120}$")
RELEASE = re.compile(r"^[A-Za-z0-9._-]{1,80}$")


def fail(message: str) -> None:
    print(f"app routes: {message}", file=sys.stderr)
    sys.exit(2)


def value_ok(text: str) -> bool:
    return bool(VALUE.match(text)) and not any(c in text for c in '"\\${}')


def regex_ok(text: str) -> bool:
    if not isinstance(text, str) or not 1 <= len(text) <= 300 or not VALUE.match(text):
        return False
    if '"' in text or text.endswith("\\") or ";" in text:
        return False
    # '$' only as an anchor (end of pattern, or before ')' or '|'); never a
    # variable reference.
    if re.search(r"\$(?![)|]|$)", text):
        return False
    try:
        re.compile(text)
    except re.error:
        return False
    return True


def main() -> int:
    if len(sys.argv) != 8:
        fail("usage: app_routes.py <release> <project> <port> <site-root> <release-id> <routes-out> <maps-out>")
    release, project, port, site_root, release_id, routes_out, maps_out = sys.argv[1:]
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,62}", project) or not port.isdigit() or not RELEASE.match(release_id):
        fail("invalid project, port or release id")
    var_prefix = "simai_" + project.replace("-", "_")
    manifest = {}
    path = Path(release) / ".simai" / "app.json"
    if path.is_file():
        try:
            manifest = json.loads(path.read_text())
        except (OSError, ValueError) as exc:
            fail(f"{path}: {exc}")
    proxy = (
        f"        proxy_pass http://127.0.0.1:{port};\n"
        "        proxy_http_version 1.1;\n"
        "        proxy_set_header Host $host;\n"
        "        proxy_set_header X-Real-IP $remote_addr;\n"
        "        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n"
        "        proxy_set_header X-Forwarded-Proto $scheme;\n"
        "        proxy_set_header Upgrade $http_upgrade;\n"
        "        proxy_set_header Connection $http_connection;\n"
        "        proxy_connect_timeout 5s;\n"
        "        proxy_read_timeout 300s;\n"
        "        proxy_send_timeout 300s;\n"
        "        client_max_body_size 16m;\n"
    )
    static = manifest.get("static")
    out = ["# simai-app-routes (generated by simai-env from .simai/app.json; do not edit)\n"]
    maps = ["# simai-app-maps (generated by simai-env from .simai/app.json; do not edit)\n"]
    if not static:
        out.append("    location / {\n" + proxy + "    }\n")
        Path(routes_out).write_text("".join(out))
        Path(maps_out).write_text("".join(maps))
        return 0
    if not isinstance(static, dict):
        fail("static must be an object")
    root = static.get("root", "public")
    if not isinstance(root, str) or not re.fullmatch(r"[A-Za-z0-9._-][A-Za-z0-9._/-]{0,100}", root) or ".." in root.split("/"):
        fail("static.root must be a relative directory")
    docroot = f"{site_root}/current/{root.rstrip('/')}"
    fallback = static.get("fallback", "404")
    if fallback != "404" and not (isinstance(fallback, str) and PATH.match(fallback)):
        fail("static.fallback must be a path such as /index.html or \"404\"")

    sets = manifest.get("headers", {})
    if not isinstance(sets, dict):
        fail("headers must be an object of named header sets")
    for set_name, headers in sets.items():
        if not NAME.match(set_name) or not isinstance(headers, dict):
            fail(f"invalid header set {set_name!r}")
        for header, value in headers.items():
            if header.lower() not in HEADER_NAMES:
                fail(f"header {header!r} is not allowed (allowed: {', '.join(sorted(HEADER_NAMES))})")
            if not isinstance(value, str) or not value_ok(value):
                fail(f"invalid value for header {header}")

    release_header = manifest.get("release_header")
    if release_header is not None and (not isinstance(release_header, str) or not re.fullmatch(r"X-[A-Za-z0-9-]{1,60}", release_header)):
        fail("release_header must look like X-App-Release")

    rules = manifest.get("cache", {})
    if not isinstance(rules, dict):
        fail("cache must be an object of named rules")
    rule_vars = {}
    for rule, spec in rules.items():
        if not NAME.match(rule) or not isinstance(spec, dict):
            fail(f"invalid cache rule {rule!r}")
        value, default = spec.get("value", ""), spec.get("default", "no-cache")
        if not CACHE_VALUE.match(str(value)) or not CACHE_VALUE.match(str(default)):
            fail(f"cache rule {rule}: value and default must be Cache-Control values")
        var = f"${var_prefix}_{rule.replace('-', '_')}"
        if "arg" in spec:
            if not ARG.match(str(spec["arg"])) or not isinstance(spec.get("values"), list):
                fail(f"cache rule {rule}: arg needs a name and a list of values")
            body = [f'    default "{default}";\n']
            for item in spec["values"]:
                if not isinstance(item, str) or not TOKEN.match(item):
                    fail(f"cache rule {rule}: invalid value {item!r}")
                body.append(f'    "{item}" "{value}";\n')
            maps.append(f"map $arg_{spec['arg']} {var} {{\n" + "".join(body) + "}\n")
        elif "uri" in spec:
            if not regex_ok(spec["uri"]):
                fail(f"cache rule {rule}: invalid uri pattern")
            maps.append(f'map $uri {var} {{\n    default "{default}";\n    "~{spec["uri"]}" "{value}";\n}}\n')
        else:
            fail(f"cache rule {rule}: needs arg or uri")
        rule_vars[rule] = var

    def cache_directive(name):
        if name is None:
            return ""
        if name in rule_vars:
            return f"        add_header Cache-Control {rule_vars[name]} always;\n"
        if isinstance(name, str) and CACHE_VALUE.match(name):
            return f'        add_header Cache-Control "{name}" always;\n'
        fail(f"unknown cache rule {name!r}")

    def header_lines(names, cors=False):
        lines, seen = [], set()
        for set_name in names or []:
            if set_name not in sets:
                fail(f"unknown header set {set_name!r}")
            for header, value in sets[set_name].items():
                lines.append(f'        add_header {header} "{value}" always;\n')
                seen.add(header.lower())
        if cors:
            lines.append('        add_header Access-Control-Allow-Origin "*" always;\n')
            lines.append('        add_header Cross-Origin-Resource-Policy "cross-origin" always;\n')
            seen.update({"access-control-allow-origin", "cross-origin-resource-policy"})
        if "x-content-type-options" not in seen:
            lines.append('        add_header X-Content-Type-Options "nosniff" always;\n')
        if release_header:
            lines.append(f'        add_header {release_header} "{release_id}" always;\n')
        return "".join(lines)

    gzip_types = manifest.get("gzip_types", ["text/css", "application/javascript", "application/json", "image/svg+xml", "text/plain", "text/xml"])
    if not isinstance(gzip_types, list) or not all(isinstance(t, str) and MIME.match(t) for t in gzip_types):
        fail("gzip_types must be a list of MIME types")
    # Text answers carry their encoding, as on the static profile.
    out.append("    charset utf-8;\n    charset_types text/html text/plain text/xml text/css application/javascript application/json image/svg+xml;\n")
    out.append("    gzip on;\n    gzip_vary on;\n    gzip_proxied any;\n    gzip_min_length 1024;\n")
    out.append(f"    gzip_types {' '.join(gzip_types)};\n")

    # Deny rules run at server level, before location selection, so they also
    # cover paths inside ^~ prefix locations (where regex locations do not
    # apply). Hidden files are always denied, except ACME challenges.
    out.append('    if ($uri ~ "/\\.(?!well-known/)") {\n        return 404;\n    }\n')
    for pattern in manifest.get("deny", []):
        if not regex_ok(pattern):
            fail(f"invalid deny pattern {pattern!r}")
        out.append(f'    if ($uri ~* "{pattern}") {{\n        return 404;\n    }}\n')

    for route in manifest.get("routes", []):
        if not isinstance(route, dict) or route.get("to") != "service" or not PATH.match(str(route.get("path", ""))):
            fail("each route needs a path prefix and \"to\": \"service\"")
        out.append(f"    location {route['path']} {{\n" + proxy + header_lines(route.get("headers")) + "    }\n")

    for loc in manifest.get("locations", []):
        if not isinstance(loc, dict) or not PATH.match(str(loc.get("path", ""))):
            fail("each location needs a path")
        modifier = "=" if loc.get("exact") else "^~"
        body = f"        root {docroot};\n"
        if "default_type" in loc:
            if not MIME.match(str(loc["default_type"])):
                fail(f"invalid default_type in {loc['path']}")
            body += f"        default_type {loc['default_type']};\n"
        body += header_lines(loc.get("headers"), bool(loc.get("cors")))
        body += cache_directive(loc.get("cache"))
        try_mode = loc.get("try", "file")
        if try_mode not in ("file", "dir"):
            fail(f"try must be file or dir in {loc['path']}")
        body += "        try_files $uri $uri/ =404;\n" if try_mode == "dir" else "        try_files $uri =404;\n"
        out.append(f"    location {modifier} {loc['path']} {{\n" + body + "    }\n")

    page = manifest.get("page", {})
    if not isinstance(page, dict):
        fail("page must be an object")
    body = f"        root {docroot};\n" + header_lines(page.get("headers")) + cache_directive(page.get("cache", "no-cache"))
    body += "        try_files $uri $uri/ " + ("=404" if fallback == "404" else fallback) + ";\n"
    out.append("    location / {\n" + body + "    }\n")
    Path(routes_out).write_text("".join(out))
    Path(maps_out).write_text("".join(maps))
    return 0


if __name__ == "__main__":
    sys.exit(main())
